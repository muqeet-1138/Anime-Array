#!/usr/bin/env node
/**
 * make-sitemap.mjs
 *
 * Generates docs/sitemap.xml from the files actually on disk.
 *
 * Why generated rather than hand-written: a sitemap that lists a URL which does
 * not exist, or omits one that does, is the most common way a sitemap becomes
 * unreadable. Deriving it from the filesystem removes the possibility.
 *
 * Rules applied, all of them things Google actually cares about:
 *
 *   - Only indexable pages are listed. Anything with noindex is excluded, and
 *     the 404 page is excluded because a URL that returns 404 must never be
 *     submitted.
 *   - lastmod is the file's real modification time, in full W3C datetime with a
 *     timezone. Google accepts a bare date but the full form is unambiguous and
 *     lets Google trust the value enough to use it for crawl scheduling.
 *   - changefreq and priority are deliberately NOT emitted. Google states it
 *     ignores both, so they are noise that tools flag as unmaintained metadata.
 *   - Verification stubs are skipped. They are not pages.
 *   - URLs are absolute and canonical, matching each page's own canonical link.
 *
 * Run:  node tools/make-sitemap.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DOCS = path.join(ROOT, 'docs');
const ORIGIN = process.argv[2] || 'https://muqeet-1138.github.io/Anime-Array';

const isStub = (f) => /^google[0-9a-f]+\.html$/i.test(f) || /verification/i.test(f);

function isNoindex(file) {
    return /<meta[^>]+name=["']robots["'][^>]*noindex/i.test(fs.readFileSync(path.join(DOCS, file), 'utf8'));
}

function canonicalOf(file) {
    const html = fs.readFileSync(path.join(DOCS, file), 'utf8');
    return (html.match(/rel=["']canonical["'][^>]*href=["']([^"']+)/i) || [])[1] || null;
}

/** W3C datetime, the form Google prefers, taken from the file's mtime. */
function w3c(file) {
    return new Date(fs.statSync(path.join(DOCS, file)).mtime).toISOString().replace(/\.\d{3}Z$/, 'Z');
}

const candidates = fs.readdirSync(DOCS).filter((f) => f.endsWith('.html') && !isStub(f));

const included = [];
const excluded = [];

for (const file of candidates) {
    // 404 pages must never be submitted.
    if (file === '404.html') { excluded.push(`${file} (a 404 must not be submitted)`); continue; }
    if (isNoindex(file)) { excluded.push(`${file} (noindex)`); continue; }
    if (!canonicalOf(file)) { excluded.push(`${file} (no canonical link, so its URL is ambiguous)`); continue; }
    included.push({ file, url: canonicalOf(file), lastmod: w3c(file) });
}

// Home page first, then alphabetical, which is stable and diff-friendly.
included.sort((a, b) => (a.url === `${ORIGIN}/` ? -1 : b.url === `${ORIGIN}/` ? 1 : a.file.localeCompare(b.file)));

const lines = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!--',
    '  Generated by tools/make-sitemap.mjs. Do not edit by hand.',
    '  Run `node tools/make-sitemap.mjs` after adding, renaming or removing a page.',
    '-->',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ''
];

for (const e of included) {
    lines.push('  <url>');
    lines.push(`    <loc>${e.url}</loc>`);
    lines.push(`    <lastmod>${e.lastmod}</lastmod>`);
    lines.push('  </url>');
    lines.push('');
}
lines.push('</urlset>');
lines.push('');

fs.writeFileSync(path.join(DOCS, 'sitemap.xml'), lines.join('\n'), 'utf8');

console.log(`sitemap.xml written: ${included.length} URL(s)`);
included.forEach((e) => console.log(`  ${e.lastmod}  ${e.url}`));
if (excluded.length) {
    console.log('\nexcluded:');
    excluded.forEach((x) => console.log(`  ${x}`));
}